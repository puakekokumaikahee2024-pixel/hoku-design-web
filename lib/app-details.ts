export type AppFeature = {
  title: string;
  body?: string;
  /** 箇条書きで並べる項目 */
  items?: string[];
};

export type PricePlan = {
  name: string;
  price: number;
  currency: "JPY" | "USD";
  /** 月額なら "monthly"、買い切りなら "one-time"。無料プランは省略 */
  billing?: "monthly" | "one-time";
};

export type AppDetail = {
  /** title の真ん中に入る「用途がわかる説明」 */
  seoPurpose: string;
  /** meta description（検索キーワードを自然に含める） */
  seoDescription: string;
  /** ヒーローのキャッチコピー */
  catchcopy: string;
  /** 概要（3〜4文） */
  overview: string[];
  /** 主な機能（4〜6個） */
  features: AppFeature[];
  /** こんな方におすすめ（3つ） */
  audience: string[];
  /** schema.org の applicationCategory */
  schemaCategory: "MedicalApplication" | "TravelApplication" | "GameApplication";
  /** 料金（ページ表示用）。不明なら省略 */
  pricing?: string;
  /** JSON-LD の offers に入れる料金プラン。金額がわからないものは入れない */
  plans?: PricePlan[];
  /** 対応言語 */
  languages?: string;
  /** 対応環境の補足 */
  requirementsNote?: string;
};

